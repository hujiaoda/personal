_SCHEMA = """
DROP TABLE IF EXISTS expenses;
CREATE TABLE expenses (
    id INTEGER PRIMARY KEY,
    日期 TEXT NOT NULL,
    类别 TEXT NOT NULL,
    项目 TEXT NOT NULL,
    金额 REAL NOT NULL,
    支付方式 TEXT,
    备注 TEXT
);

DROP TABLE IF EXISTS study_logs;
CREATE TABLE study_logs (
    id INTEGER PRIMARY KEY,
    日期 TEXT NOT NULL,
    科目 TEXT NOT NULL,
    主题 TEXT NOT NULL,
    时长分钟 INTEGER NOT NULL,
    渠道 TEXT,
    是否完成 INTEGER NOT NULL DEFAULT 1,
    笔记 TEXT
);

DROP TABLE IF EXISTS movie_logs;
CREATE TABLE movie_logs (
    id INTEGER PRIMARY KEY,
    观看日期 TEXT NOT NULL,
    片名 TEXT NOT NULL,
    类型 TEXT NOT NULL,
    年份 INTEGER NOT NULL,
    评分 REAL NOT NULL,
    时长分钟 INTEGER NOT NULL,
    平台 TEXT,
    短评 TEXT
);
"""


def build_demo_tables(db_path: str) -> str:
    """确定性生成 data/user_tables.db 的三张演示表；重复执行等同重建。"""
    path = Path(db_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    import sqlite3

    conn = sqlite3.connect(path)
    try:
        conn.executescript(_SCHEMA)
        conn.executemany(
            "INSERT INTO expenses(日期, 类别, 项目, 金额, 支付方式, 备注) "
            "VALUES (?, ?, ?, ?, ?, ?)",
            _EXPENSES,
        )
        conn.executemany(
            "INSERT INTO study_logs(日期, 科目, 主题, 时长分钟, 渠道, 是否完成, 笔记) "
            "VALUES (?, ?, ?, ?, ?, ?, ?)",
            _STUDY_LOGS,
        )
        conn.executemany(
            "INSERT INTO movie_logs(观看日期, 片名, 类型, 年份, 评分, 时长分钟, 平台, 短评) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            _MOVIE_LOGS,
        )
        conn.commit()
    finally:
        conn.close()
    return str(path)


